// Tiny jitter (±0.3°) so co-located validators don't stack on top of each other
function jitter(coord, seed) {
  const r = ((seed * 9301 + 49297) % 233280) / 233280
  return coord + (r - 0.5) * 0.6
}

export function getValidatorLocation(_name, id) {
  const base = LOCATIONS[id]
  if (base) return [jitter(base[0], id * 7), jitter(base[1], id * 13)]
  // Fallback for IDs without an explicit row (new validators)
  return [jitter(10, id * 7), jitter(45, id * 13)]
}
